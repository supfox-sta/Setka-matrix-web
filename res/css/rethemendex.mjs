#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const cssDir = path.dirname(fileURLToPath(import.meta.url));
const excluded = new Set(["_components.pcss", "_index.pcss"]);

function collectPcssFiles(dir) {
    /** @type {string[]} */
    const files = [];

    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            files.push(...collectPcssFiles(fullPath));
            continue;
        }

        if (!entry.name.startsWith("_") || !entry.name.endsWith(".pcss")) {
            continue;
        }
        if (excluded.has(entry.name)) {
            continue;
        }

        files.push(path.relative(cssDir, fullPath).split(path.sep).join("/"));
    }

    return files;
}

const imports = collectPcssFiles(cssDir).sort((a, b) => a.localeCompare(b, "en"));
const lines = ["/* autogenerated by rethemendex.mjs */", ...imports.map((file) => `@import "./${file}";`), ""];
fs.writeFileSync(path.join(cssDir, "_components.pcss"), lines.join("\n"));
